#!/usr/bin/env node
/**
 * Regenerate docs/RULES.md from score/rules.js.
 * Run from the repo root: node scripts/generate-rules-md.js
 */
'use strict';

var fs = require('fs');
var path = require('path');
var rules = require('../score/rules.js');

var GROUPS = [
  ['lineRules', 'Line'],
  ['specialRules', 'Special'],
  ['pathRules', 'Path'],
  ['fileRules', 'File'],
  ['repoRules', 'Repo']
];

var rows = [];
GROUPS.forEach(function (g) {
  (rules[g[0]] || []).forEach(function (rule) {
    if (!rule.id || !rule.sev || !rule.cat || !rule.title) {
      throw new Error('Rule in ' + g[0] + ' is missing id, sev, cat, or title: ' + JSON.stringify(rule && rule.id));
    }
    if (!rules.CATEGORIES[rule.cat]) {
      throw new Error(rule.id + ' uses unknown category ' + rule.cat);
    }
    rows.push({
      id: rule.id,
      sev: rule.sev,
      cat: rule.cat,
      catName: rules.CATEGORIES[rule.cat].name,
      title: rule.title,
      source: g[1]
    });
  });
});

var seen = {};
rows.forEach(function (r) {
  if (seen[r.id]) throw new Error('Duplicate rule id ' + r.id);
  seen[r.id] = true;
});
rows.sort(function (a, b) { return a.id < b.id ? -1 : a.id > b.id ? 1 : 0; });

function cell(s) {
  return String(s).replace(/&/g, '&amp;').replace(/\|/g, '\\|').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\r?\n/g, ' ');
}

var catOrder = ['secrets', 'code', 'prompt', 'docs'];
var byCat = {};
rows.forEach(function (r) {
  (byCat[r.cat] = byCat[r.cat] || []).push(r);
});

var rs = rules.RULESET;
var lines = [];
lines.push('# Pushy Score rules');
lines.push('');
lines.push('Generated from [`score/rules.js`](../score/rules.js). Do not edit this file by hand. After a ruleset change, run `node scripts/generate-rules-md.js` from the repo root and commit the result with the ruleset bump.');
lines.push('');
lines.push('| | |');
lines.push('| --- | --- |');
lines.push('| Ruleset | `' + rs.id + '` ' + rs.version + ' (' + rs.date + ') |');
lines.push('| Rules | ' + rows.length + ' |');
lines.push('');
lines.push('Each table lists the declared severity on the rule. That is the severity before the docs / test / example downgrade. Some rules then set a different severity on an individual hit. Those cases are listed under [Severity on a hit](#severity-on-a-hit).');
lines.push('');
lines.push('The description column is the rule `title` from `rules.js` (what the finding is called in the scanner).');
lines.push('');

catOrder.forEach(function (cat) {
  var list = byCat[cat] || [];
  var meta = rules.CATEGORIES[cat];
  lines.push('## ' + meta.name);
  lines.push('');
  var hint = meta.hint.charAt(0).toUpperCase() + meta.hint.slice(1);
  lines.push(hint + '. ' + list.length + ' rule' + (list.length === 1 ? '' : 's') + '.');
  lines.push('');
  lines.push('| ID | Severity | Category | Description |');
  lines.push('| --- | --- | --- | --- |');
  list.forEach(function (r) {
    lines.push('| `' + cell(r.id) + '` | ' + cell(r.sev) + ' | ' + cell(r.catName) + ' | ' + cell(r.title) + ' |');
  });
  lines.push('');
});

lines.push('## Where each rule runs');
lines.push('');
lines.push('| ID | Runner |');
lines.push('| --- | --- |');
rows.forEach(function (r) {
  lines.push('| `' + r.id + '` | ' + r.source + ' |');
});
lines.push('');
lines.push('Runners match the arrays in `rules.js`: line (regex or nearby-line patterns on file text), special (custom scan of one file), path (file name and kind only), file (structure of one file), repo (metadata, tree, and whole-scan checks).');
lines.push('');
lines.push('## Severity on a hit');
lines.push('');
lines.push('Declared severity is what the tables above show. The engine can still change the severity that is scored:');
lines.push('');
lines.push('- On a docs, example, sample, demo, or non-core README-like path, prompt and code hits drop one level (`critical` to `high`, `high` to `medium`, `medium` to `low`; `low` and `info` stay). Paths covered are `tests`, `__tests__`, `spec`, `fixtures`, `examples`, `samples`, `docs`, `demo`, `demos`, `testdata`, plus a root-or-nested file whose name starts with `readme`, `changelog`, `contributing`, or `code_of_conduct`. Core instruction files (`SKILL.md`, `AGENTS.md`, `CLAUDE.md`, `GEMINI.md`, `.cursorrules`, `.windsurfrules`, `.clinerules`, `copilot-instructions.md`, `*.prompt.md`, `*.mdc`) are not downgraded.');
lines.push('- On a test path (`tests`, `__tests__`, `spec`, `fixtures`, `testdata`, or a `*.test.*` / `*.spec.*` file), code rules whose id starts with `X` drop one further level. The finding note calls that a two-level drop.');
lines.push('- `P011` sets `noEscapeCtx`, so the downgrades above do not apply to it. Tag characters are scored `critical`, bidi overrides `high`, and zero-width characters `medium`.');
lines.push('- `P012` scores a base64 blob `high` when the decoded text looks like a shell, eval, secret, or instruction payload. Other blobs in instruction files stay `medium`. Other opaque blobs are `low`.');
lines.push('- `D005` stays `medium` for missing frontmatter, `name`, or `description`. A `name` that is not lowercase-hyphen, or a `description` over 1024 characters, is `low`.');
lines.push('- `M002` is `medium` when the latest commit is more than 365 days old, and `low` when it is more than 180 days old. Archived repos skip this rule.');
lines.push('- `A002` stays `high` for `defaultMode: bypassPermissions` and for a VS Code task with `runOn: folderOpen`. Broad `allow` rules, `enableAllProjectMcpServers: true`, and hooks are `medium`.');
lines.push('- `A003` scores a shell `-c` launch and a privileged or host-mounted container `high`. A remote server on plain `http` (other than loopback) is `medium`. An unpinned `npx`, `bunx`, `uvx`, or `pipx` package is `low`.');
lines.push('- `A004` scores an install hook `high` when the script matches curl, wget, a URL, `node -e`, powershell, base64, eval, or `sh -c`. Other `preinstall`, `install`, and `postinstall` hooks are `medium`. `prepare`, `prepublish`, and `prepack` hooks that are not a plain build or `husky` are `low`. A plain build or `husky` on those three hooks is not flagged. Git, URL, file, ssh, or GitHub-shorthand dependencies are `medium`. `*`, `latest`, or an empty range is `low`.');
lines.push('- `A005` scores an extra index or `--trusted-host` `medium`, and an unpinned `git+` requirement `low`.');
lines.push('- `A006` scores event-text script injection and `pull_request_target` plus a checkout of the PR head `high`. `permissions: write-all` is `medium`.');
lines.push('');
lines.push('Info findings use a penalty of 0. `N005` is informational and does not change the score.');
lines.push('');

var out = lines.join('\n');
var dest = path.join(__dirname, '..', 'docs', 'RULES.md');
fs.writeFileSync(dest, out);
console.log('Wrote ' + dest + ' (' + rows.length + ' rules, ruleset ' + rs.version + ')');
